  function normalizeLanguage(language) {
    return language === 'en' ? 'en' : DEFAULT_LANGUAGE;
  }

  function translate(language, key, values = {}) {
    const normalizedLanguage = normalizeLanguage(language);
    const template = catalogs[normalizedLanguage][key] ?? catalogs[DEFAULT_LANGUAGE][key] ?? key;
    return template.replace(/\{([a-zA-Z][\w]*)\}/g, (match, name) => (
      Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match
    ));
  }

  function htmlLanguage(language) {
    return normalizeLanguage(language) === 'en' ? 'en' : 'zh-CN';
  }

  return {
    LANGUAGE_STORAGE_KEY,
    DEFAULT_LANGUAGE,
    catalogs,
    htmlLanguage,
    normalizeLanguage,
    translate,
  };
